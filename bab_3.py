# Integer (int)
umur = 25
print(type(umur))

# Float 
tinggi = 170.5
print(type(tinggi))  

# String (str)
nama = "Nadya"
print(type(nama)) 

# Boolean (bool)
is_active = True
print(type(is_active)) 

# List
buah = ["apel", "jeruk", "mangga"]
print(type(buah))

# Tuple
warna = ("merah", "hijau", "biru")
print(type(warna))

# Dictionary (dict)
mahasiswa = {"nama": "Budi", "umur": 21, "jurusan": "Informatika"}
print(type(mahasiswa)) 

# Set 
angka = {1, 2, 3, 3, 4}
print(angka) 
print(type(angka))

# Konvigurasi Tipe Data
x = 10       
y = float(x) 
z = str(x) 

print(y, type(y))  

