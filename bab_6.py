# Operator aritmatika
a = 10
b = 3

print(a + b)  
print(a - b)   
print(a * b)   
print(a / b)  
print(a // b)  
print(a % b)   
print(a ** b)  

# Operator perbandingan
x = 5
y = 10

print(x == y)  
print(x != y) 
print(x > y) 
print(x < y)   
print(x >= y)  
print(x <= y)  

# Operator logika
a = True
b = False

print(a and b)  
print(a or b)   
print(not a)    

# Operator penugasan
x = 10

x += 5
print(x) 

x -= 3
print(x) 

x *= 2
print(x)  

x /= 4
print(x) 

# Operator keanggotaan 
buah = ["apel", "jeruk", "mangga"]

print("apel" in buah)     
print("pisang" not in buah) 

# Operator identitas
a = [1, 2, 3]
b = a
c = [1, 2, 3]

print(a is b) 
print(a is c)     
print(a == c)  
   